import json
from pathlib import Path

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, PlainTextResponse

from app.calibration import compute_calibration
from app.models import CalibrationReport, CalibrationRequest

app = FastAPI(
    title="JudgeBench",
    description="AI-as-a-Judge reliability benchmark, bias detector, and inter-rater calibration platform.",
    version="0.1.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

WEB_DIR = Path(__file__).parent / "web"
DATASET_PATH = Path(__file__).parents[1] / "benchmarks" / "calibration_dataset.json"


@app.get("/health", include_in_schema=False)
def health():
    return {"status": "ok", "service": "judgebench"}


@app.get("/api/benchmark-dataset")
def get_benchmark_dataset():
    if not DATASET_PATH.exists():
        return {"items": []}
    return json.loads(DATASET_PATH.read_text(encoding="utf-8"))


@app.post("/api/calibrate", response_model=CalibrationReport)
def calibrate(request: CalibrationRequest):
    return compute_calibration(request)


@app.post("/api/reports/markdown")
def generate_markdown(request: CalibrationRequest):
    report = compute_calibration(request)
    agr = report.agreement
    bias = report.bias

    rows = []
    for c in report.adjudication_queue:
        rows.append(
            f"| `{c.pair_id}` | {c.human_score} | {c.judge_score} | `{c.absolute_gap}` | {c.severity_note} |"
        )
    rows_text = (
        "\n".join(rows)
        if rows
        else "| None | - | - | - | All pair ratings agree within threshold |"
    )

    pearson_disp = f"{agr.pearson_correlation:.4f}" if agr.pearson_correlation is not None else "N/A"
    kappa_disp = f"{agr.cohen_weighted_kappa:.4f}" if agr.cohen_weighted_kappa is not None else "N/A"
    verbosity_disp = (
        f"{bias.verbosity_bias_correlation:.4f}"
        if bias.verbosity_bias_correlation is not None
        else "N/A"
    )

    md = f"""# JudgeBench - Evaluator Calibration & Reliability Audit

**Human Baseline:** `{report.human_rater_id}`  
**AI Judge Model:** `{report.judge_model_id}`  
**Reliability Classification:** `{report.reliability_tier}`  

---

## 1. Inter-Rater Agreement Statistics (Sample: {agr.pair_count} pairs)
- **Mean Absolute Error (MAE):** `{agr.mean_absolute_error}`
- **Root Mean Square Error (RMSE):** `{agr.root_mean_square_error}`
- **Pearson Correlation (r):** `{pearson_disp}`
- **Quadratic Weighted Kappa (kappa):** `{kappa_disp}`
- **Exact Match Agreement:** `{round(agr.exact_match_ratio * 100, 1)}%`
- **Within 1.0 Point Agreement:** `{round(agr.within_one_point_ratio * 100, 1)}%`

---

## 2. Systematic Evaluator Bias Analysis
- **Judge Score Inflation (Mean Error):** `{bias.judge_systematic_inflation:+0.3f}`
- **Verbosity Bias Correlation:** `{verbosity_disp}`
- **Severe Disagreements Requiring Adjudication:** `{bias.severe_disagreements}`

---

## 3. Disagreement Adjudication Queue
| Pair ID | Human Score | Judge Score | Gap | Reviewer Note |
|---|---|---|---|---|
{rows_text}

_Generated by JudgeBench Calibration Platform v0.1.0_
"""
    return PlainTextResponse(md, media_type="text/markdown")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(WEB_DIR / "index.html")


@app.get("/app.js", include_in_schema=False)
def javascript():
    return FileResponse(WEB_DIR / "app.js", media_type="text/javascript")


@app.get("/style.css", include_in_schema=False)
def stylesheet():
    return FileResponse(WEB_DIR / "style.css", media_type="text/css")
